function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="te">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  useEffect(() => { void setupOfflineSupport().catch(() => {}); }, []);
  useEffect(() => { restoreLanguage(); }, []);
  useEffect(() => installBellAudioUnlock(), []);
  useEffect(() => {
    let refresh: ReturnType<typeof setTimeout> | undefined;
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      // Leave the auth client's lock before refetches call getSession/getUser.
      clearTimeout(refresh);
      refresh = setTimeout(() => {
        if (event === "SIGNED_OUT") queryClient.clear();
        else void queryClient.invalidateQueries();
        void router.invalidate();
      }, 0);
    });
    return () => { clearTimeout(refresh); data.subscription.unsubscribe(); };
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <AccountBlockGate><ProfileAccessGate><Outlet /></ProfileAccessGate><PushSoundSync /><Referral /></AccountBlockGate>
      <AccountIncomingNotice />
      <SubscriptionActionGate />
      <Toaster position="top-center" richColors />
    </QueryClientProvider>
  );
}
function AccountIncomingNotice() {
  const { data: me } = useMe();
  return me ? <IncomingNotice key={me.id} userId={me.id} /> : null;
}
